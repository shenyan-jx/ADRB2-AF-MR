cat("STEP2 outcome rows =", ifelse(is.null(out),0,nrow(out)), "\n")
print(out[, c("SNP","effect_allele.outcome","other_allele.outcome","beta.outcome","se.outcome","pval.outcome","eaf.outcome")])
saveRDS(out, "mr_adrb1/outcome_AF.rds")
