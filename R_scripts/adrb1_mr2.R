cat("STEP3 harmonised =", nrow(dat), " mr_keep =", sum(dat$mr_keep), "\n")
print(dat[, c("SNP","beta.exposure","beta.outcome","palindromic","ambiguous","mr_keep")])
saveRDS(dat, "mr_adrb1/dat_harmonised.rds")
